#!/usr/bin/env node
/**
 * Sinkronkan data harga dari seed-data/pricing.json ke database mana pun (local, staging, produksi)
 * dalam bentuk SQL yang bisa ditinjau dulu. Tanpa dependensi (Node murni).
 *
 *   node server/prisma/pricing-sync.mjs > /tmp/pricing-sync.sql     # SQL upsert
 *   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f /tmp/pricing-sync.sql
 *   node server/prisma/pricing-sync.mjs --fallback                  # tulis ulang src/data/pricing-fallback.ts
 *
 * Aturan SQL (satu transaksi, aman dijalankan berulang):
 * - HANYA menyentuh tabel PriceRegion, PricingScheme, PriceEntry, PricingTerms dan baris Setting
 *   `pricing_settings`. Tabel lain tidak disentuh.
 * - Upsert per kunci alami (slug wilayah/skema, wilayah × skema × model × varian): nilai di seed
 *   menimpa nilai di DB. Baris yang TIDAK ada di seed (mis. tambahan admin) dibiarkan.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const seed = JSON.parse(readFileSync(path.join(here, "seed-data", "pricing.json"), "utf8"));

// Default yang sama dengan server/src/modules/pricing/pricing.settings.ts
const SETTINGS = {
  disclaimerId: "Harga dan promo dapat berubah sewaktu-waktu, terbatas waktu dan kuota. Penawaran tertulis diberikan di showroom.",
  disclaimerEn: "Prices and promotions may change at any time and are limited by time and quota. Written offers are provided at the showroom.",
  supercharge: {
    enabled: true,
    unitId: "per sekali charge",
    unitEn: "per charging session",
    tariff: { bees: null, athena: 16500, victory: 16500, edpower: 27000 },
    noteId: "±15 menit dari 15% ke 95%. Tarif sama di semua stasiun SuperCharge.",
    noteEn: "About 15 minutes from 15% to 95%. The same tariff applies at every SuperCharge station.",
  },
  referral: {
    enabled: true,
    amount: 300000,
    regionSlugs: ["jabodetabek"],
    titleId: "Program Referral",
    titleEn: "Referral Programme",
    descriptionId: "Bonus Rp 300.000 untuk setiap orang yang Anda referensikan dan memenuhi syarat. Siapa saja boleh ikut, tidak harus pengguna Wedison. Dicairkan maksimal 2 minggu setelah serah terima unit.",
    descriptionEn: "A Rp 300,000 bonus for every person you refer who qualifies. Anyone can take part, not only Wedison owners. Paid out within 2 weeks of unit handover.",
  },
};

const NUM = ["otrPrice", "discount", "netPrice", "dailyFee", "downPayment", "termMonths", "installment24", "installment36", "unitPrice", "monthlyFee"];

// ─── SQL ────────────────────────────────────────────────────────────────────
function q(v) {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
}
const arr = (xs) => (xs?.length ? `ARRAY[${xs.map(q).join(", ")}]::text[]` : "ARRAY[]::text[]");
const ts = (v) => (v ? `${q(v)}::timestamp` : "NULL");
const region = (slug) => `(SELECT "id" FROM "PriceRegion" WHERE "slug" = ${q(slug)})`;
const scheme = (slug) => `(SELECT "id" FROM "PricingScheme" WHERE "slug" = ${q(slug)})`;

function sql() {
  const out = ["-- Generated by server/prisma/pricing-sync.mjs from seed-data/pricing.json", "BEGIN;", ""];

  out.push("-- Wilayah");
  for (const r of seed.regions) {
    out.push(`INSERT INTO "PriceRegion" ("id","slug","nameId","nameEn","priceLabelId","priceLabelEn","coverageId","coverageEn","salesWhatsapp","isDefault","isActive","sortOrder","createdAt","updatedAt")
VALUES (${q(`prg_${r.slug}`)}, ${q(r.slug)}, ${q(r.nameId)}, ${q(r.nameEn)}, ${q(r.priceLabelId)}, ${q(r.priceLabelEn)}, ${q(r.coverageId)}, ${q(r.coverageEn)}, ${q(r.salesWhatsapp)}, ${q(r.isDefault)}, true, ${q(r.sortOrder)}, NOW(), NOW())
ON CONFLICT ("slug") DO UPDATE SET "nameId"=EXCLUDED."nameId","nameEn"=EXCLUDED."nameEn","priceLabelId"=EXCLUDED."priceLabelId","priceLabelEn"=EXCLUDED."priceLabelEn","coverageId"=EXCLUDED."coverageId","coverageEn"=EXCLUDED."coverageEn","salesWhatsapp"=EXCLUDED."salesWhatsapp","isDefault"=EXCLUDED."isDefault","isActive"=true,"sortOrder"=EXCLUDED."sortOrder","updatedAt"=NOW();`);
  }
  const def = seed.regions.find((r) => r.isDefault);
  if (def) out.push(`UPDATE "PriceRegion" SET "isDefault"=false, "updatedAt"=NOW() WHERE "isDefault" AND "slug" <> ${q(def.slug)};`);

  out.push("", "-- Skema");
  for (const s of seed.schemes) {
    out.push(`INSERT INTO "PricingScheme" ("id","slug","kind","nameId","nameEn","taglineId","taglineEn","descriptionId","descriptionEn","audience","isPublic","isActive","sortOrder","createdAt","updatedAt")
VALUES (${q(`psc_${s.slug}`)}, ${q(s.slug)}, ${q(s.kind)}::"PricingSchemeKind", ${q(s.nameId)}, ${q(s.nameEn)}, ${q(s.taglineId)}, ${q(s.taglineEn)}, ${q(s.descriptionId)}, ${q(s.descriptionEn)}, ${q(s.audience)}::"PricingAudience", ${q(s.isPublic)}, true, ${q(s.sortOrder)}, NOW(), NOW())
ON CONFLICT ("slug") DO UPDATE SET "kind"=EXCLUDED."kind","nameId"=EXCLUDED."nameId","nameEn"=EXCLUDED."nameEn","taglineId"=EXCLUDED."taglineId","taglineEn"=EXCLUDED."taglineEn","descriptionId"=EXCLUDED."descriptionId","descriptionEn"=EXCLUDED."descriptionEn","audience"=EXCLUDED."audience","isPublic"=EXCLUDED."isPublic","isActive"=true,"sortOrder"=EXCLUDED."sortOrder","updatedAt"=NOW();`);
  }

  out.push("", "-- Baris harga");
  for (const e of seed.entries) {
    const v = e.variant ?? "SINGLE";
    const id = `pen_${e.region}_${e.scheme}_${e.model}_${v}`.toLowerCase();
    out.push(`INSERT INTO "PriceEntry" ("id","regionId","schemeId","model","variant",${NUM.map((k) => `"${k}"`).join(",")},"isActive","updatedAt")
VALUES (${q(id)}, ${region(e.region)}, ${scheme(e.scheme)}, ${q(e.model)}::"ProductModel", ${q(v)}::"BatteryVariant", ${NUM.map((k) => q(e[k] ?? null)).join(", ")}, true, NOW())
ON CONFLICT ("regionId","schemeId","model","variant") DO UPDATE SET ${NUM.map((k) => `"${k}"=EXCLUDED."${k}"`).join(",")},"isActive"=true,"updatedAt"=NOW();`);
  }

  out.push("", "-- S&K / bonus");
  for (const t of seed.terms) {
    out.push(`INSERT INTO "PricingTerms" ("id","regionId","schemeId","includedId","includedEn","termsId","termsEn","partners","validFrom","validUntil","noteId","noteEn","updatedAt")
VALUES (${q(`ptm_${t.region}_${t.scheme}`)}, ${region(t.region)}, ${scheme(t.scheme)}, ${arr(t.includedId)}, ${arr(t.includedEn)}, ${arr(t.termsId)}, ${arr(t.termsEn)}, ${arr(t.partners)}, ${ts(t.validFrom)}, ${ts(t.validUntil)}, ${q(t.noteId)}, ${q(t.noteEn)}, NOW())
ON CONFLICT ("regionId","schemeId") DO UPDATE SET "includedId"=EXCLUDED."includedId","includedEn"=EXCLUDED."includedEn","termsId"=EXCLUDED."termsId","termsEn"=EXCLUDED."termsEn","partners"=EXCLUDED."partners","validFrom"=EXCLUDED."validFrom","validUntil"=EXCLUDED."validUntil","noteId"=EXCLUDED."noteId","noteEn"=EXCLUDED."noteEn","updatedAt"=NOW();`);
  }

  out.push("", "-- Pengaturan (disclaimer, tarif SuperCharge, referral)");
  out.push(`INSERT INTO "Setting" ("key","value","updatedAt") VALUES ('pricing_settings', ${q(JSON.stringify(SETTINGS))}::jsonb, NOW())
ON CONFLICT ("key") DO UPDATE SET "value"=EXCLUDED."value","updatedAt"=NOW();`);

  out.push("", "COMMIT;", "");
  return out.join("\n");
}

// ─── Snapshot fallback untuk frontend ───────────────────────────────────────
function writeFallback() {
  const bi = (id, en) => (id || en ? { id: id ?? "", en: en ?? "" } : null);
  const publicSchemes = seed.schemes.filter((s) => s.isPublic);
  const pub = new Set(publicSchemes.map((s) => s.slug));
  const snapshot = {
    regions: seed.regions.map((r) => ({ slug: r.slug, name: { id: r.nameId, en: r.nameEn }, priceLabel: { id: r.priceLabelId, en: r.priceLabelEn }, coverage: bi(r.coverageId, r.coverageEn), salesWhatsapp: r.salesWhatsapp ?? null, isDefault: r.isDefault, sortOrder: r.sortOrder })),
    schemes: publicSchemes.map((s) => ({ slug: s.slug, kind: s.kind.toLowerCase(), name: { id: s.nameId, en: s.nameEn }, tagline: bi(s.taglineId, s.taglineEn), description: bi(s.descriptionId, s.descriptionEn), audience: s.audience.toLowerCase(), sortOrder: s.sortOrder })),
    entries: seed.entries.filter((e) => pub.has(e.scheme)).map((e) => ({ region: e.region, scheme: e.scheme, model: e.model.toLowerCase(), variant: (e.variant ?? "SINGLE").toLowerCase(), ...Object.fromEntries(NUM.map((k) => [k, e[k] ?? null])), note: null })),
    terms: seed.terms.filter((t) => pub.has(t.scheme)).map((t) => ({ region: t.region, scheme: t.scheme, included: { id: t.includedId, en: t.includedEn }, terms: { id: t.termsId, en: t.termsEn }, partners: t.partners, validFrom: t.validFrom, validUntil: t.validUntil, note: bi(t.noteId, t.noteEn) })),
    settings: SETTINGS,
    updatedAt: new Date().toISOString().slice(0, 10) + "T00:00:00.000Z",
  };
  const file = path.join(here, "..", "..", "src", "data", "pricing-fallback.ts");
  writeFileSync(
    file,
    `// Snapshot harga statis = jaring pengaman saat API tidak terjangkau. Bentuk sama dengan
// GET /api/v1/public/pricing. DIBUAT OTOMATIS oleh server/prisma/pricing-sync.mjs --fallback dari
// server/prisma/seed-data/pricing.json. Jangan diedit manual; ubah harga lewat /admin/pricing.
import type { PublicPricing } from "@/lib/pricing/types";

export const PRICING_FALLBACK: PublicPricing = ${JSON.stringify(snapshot, null, 2)};

export default PRICING_FALLBACK;
`,
  );
  console.error(`✔ fallback ditulis: ${snapshot.entries.length} baris, ${snapshot.terms.length} S&K`);
}

if (process.argv.includes("--fallback")) writeFallback();
else process.stdout.write(sql());
